# 2) Implement a Single layer perceptron using a tensorflow library and calculate
# the accuracy of the model on the testing data. (Use MNIST dataset)

import tensorflow as tf
import numpy as np
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Flatten, Dense
from tensorflow.keras.datasets import mnist
from sklearn.metrics import accuracy_score

# Load MNIST dataset
(x_train, y_train), (x_test, y_test) = mnist.load_data()

# Normalize the data
x_train = x_train / 255.0
x_test = x_test / 255.0

# Create Single Layer Perceptron model
model = Sequential([
    Flatten(input_shape=(28, 28)),
    Dense(10, activation='softmax')
])

# Compile the model
model.compile(
    optimizer='sgd',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# Train the model
model.fit(x_train, y_train, epochs=5)

# Evaluate the model on testing data
loss, accuracy = model.evaluate(x_test, y_test)

print("Test Accuracy:", accuracy * 100, "%")

# 3) Write a python program to implement     OR gate      using a single layer
# perceptron learning rule.

import numpy as np

# OR Gate Input and Output
X = np.array([[0, 0],
              [0, 1],
              [1, 0],
              [1, 1]])

y = np.array([0, 1, 1, 1])

# Initialize weights and bias
weights = np.zeros(2)
bias = 0
learning_rate = 0.1
epochs = 10

# Perceptron Learning Rule
for epoch in range(epochs):
    for i in range(len(X)):
        net = np.dot(X[i], weights) + bias

        # Step Activation Function
        output = 1 if net > 0 else 0

        # Calculate error
        error = y[i] - output

        # Update weights and bias
        weights = weights + learning_rate * error * X[i]
        bias = bias + learning_rate * error

# Display Output
print("OR Gate Output:")
for i in range(len(X)):
    net = np.dot(X[i], weights) + bias
    output = 1 if net > 0 else 0
    print(X[i], "=", output)

