import numpy as np
import matplotlib.pyplot as plt

# Input values
x = np.linspace(-5, 5, 200)

# Hard Tanh
def hard_tanh(x):
    return np.clip(x, -1, 1)

# Leaky ReLU
def leaky_relu(x, alpha=0.01):
    return np.where(x > 0, x, alpha * x)

# Parametric ReLU (PReLU)
def parametric_relu(x, alpha=0.25):
    return np.where(x > 0, x, alpha * x)

# ELU
def elu(x, alpha=1):
    return np.where(x >= 0, x, alpha * (np.exp(x) - 1))

# Plotting
plt.figure(figsize=(10, 8))

plt.subplot(2,2,1)
plt.plot(x, hard_tanh(x))
plt.title("Hard Tanh")
plt.grid(True)

plt.subplot(2,2,2)
plt.plot(x, leaky_relu(x))
plt.title("Leaky ReLU")
plt.grid(True)

plt.subplot(2,2,3)
plt.plot(x, parametric_relu(x))
plt.title("Parametric ReLU")
plt.grid(True)

plt.subplot(2,2,4)
plt.plot(x, elu(x))
plt.title("ELU")
plt.grid(True)

plt.tight_layout()
plt.show()

# 2) Write a python program to implement a        NAND gate          using a single layer
# perceptron learning rule.

import numpy as np

# Input
X = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1]
])

# Target Output (NAND Gate)
Y = np.array([1, 1, 1, 0])

# Initialize
weights = np.zeros(2)
bias = 0
learning_rate = 0.1
epochs = 10

print("WEIGHT UPDATION STEPS")

for epoch in range(epochs):
    for i in range(len(X)):
        x = X[i]
        target = Y[i]

        # Net Input
        net = np.dot(x, weights) + bias

        # Activation Function
        output = 1 if net >= 0 else 0

        # Error
        error = target - output

        old_weights = weights.copy()

        # Update Weights & Bias
        weights = weights + learning_rate * error * x
        bias = bias + learning_rate * error

        # Print only if weights changed
        if not np.array_equal(old_weights, weights):
            print("\n----------------------------")
            print("Input        :", x)
            print("Target       :", target)
            print("Old Weights  :", old_weights)
            print("New Weights  :", weights)

print("\n----------------------------")
print("Final Weights :", weights)
print("Final Bias    :", bias)

print("\nNAND Gate Output")
for x in X:
    net = np.dot(x, weights) + bias
    output = 1 if net >= 0 else 0
    print(x, "->", output)